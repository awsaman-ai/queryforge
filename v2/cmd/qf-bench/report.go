// renderInvariance answers a question the scale matrix raises but latency
// cannot: did the SAME sentence still produce the SAME query once the index
// held ten thousand entries?
func renderInvariance(b *strings.Builder, r *Run) {
	warm := r.Select("warm")
	if len(warm) < 2 {
		return
	}
	baseline := map[string]string{}
	baselineCode := map[string]string{}
	for _, o := range warm[0].Outcomes {
		baseline[o.ID] = o.SQLHash
		baselineCode[o.ID] = o.Code
	}

	fmt.Fprintf(b, "## Does scale change the answer?\n\n")
	fmt.Fprintf(b, "The same sentences run at every scale against the same core schema; only the\n")
	fmt.Fprintf(b, "surrounding synthetic entities grow. A changed query hash means a bigger index\n")
	fmt.Fprintf(b, "moved a reading -- a retrieval finding, not a performance one.\n\n")
	fmt.Fprintf(b, "| Scale | Cases | Identical to %s | Changed |\n|---|---|---|---|\n", warm[0].Scale.Label)
	for _, s := range warm {
		same, changed, ids := 0, 0, []string{}
		seen := map[string]bool{}
		for _, o := range s.Outcomes {
			if seen[o.ID] {
				continue
			}
			seen[o.ID] = true
			if baseline[o.ID] == o.SQLHash && baselineCode[o.ID] == o.Code {
				same++
				continue
			}
			changed++
			ids = append(ids, o.ID)
		}
		sort.Strings(ids)
		note := "-"
		if changed > 0 {
			note = strings.Join(ids, ", ")
		}
		fmt.Fprintf(b, "| %s | %d | %d | %d (%s) |\n", s.Scale.Label, same+changed, same, changed, note)
	}
	fmt.Fprintf(b, "\n")
}

func renderV1(b *strings.Builder, r *Run) {
	v1 := r.Select("v1")
	if len(v1) == 0 {
		return
	}
	fmt.Fprintf(b, "## Against the LLM architecture (v1)\n\n")
	fmt.Fprintf(b, "Fairness rules from section 17: these are DIFFERENT categories and are labelled\n")
	fmt.Fprintf(b, "as such. v1 is a remote generative model call from a process started per\n")
	fmt.Fprintf(b, "request; v2 is a warm local process. The honest comparisons are stated, not\n")
	fmt.Fprintf(b, "collapsed into one multiplier.\n\n")
	for _, s := range v1 {
		fmt.Fprintf(b, "| | |\n|---|---|\n")
		fmt.Fprintf(b, "| Requests | %d (%d succeeded, %d failed) |\n", s.Requests, s.Succeeded, s.Failed)
		fmt.Fprintf(b, "| p50 | %s |\n", humanDuration(s.Latency.P50))
		fmt.Fprintf(b, "| p95 | %s%s |\n", humanDuration(s.Latency.P95), sampleMark(s.Latency.P95UnderSampled))
		fmt.Fprintf(b, "| mean | %s |\n", humanDuration(s.Latency.Mean))
		fmt.Fprintf(b, "| min / max | %s / %s |\n", humanDuration(s.Latency.Min), humanDuration(s.Latency.Max))
		if s.Note != "" {
			fmt.Fprintf(b, "| Note | %s |\n", s.Note)
		}
		fmt.Fprintf(b, "\n")
	}

	warm := r.Select("warm")
	cold := r.Select("cold")
	if len(warm) == 0 || v1[0].Latency.N == 0 {
		return
	}

	// Section 17 asks for explicit comparison categories rather than one
	// headline multiplier. Each row says what is being compared and what is
	// not, so a reader cannot take a number out of the wrong box.
	fmt.Fprintf(b, "### The comparison categories\n\n")
	fmt.Fprintf(b, "| Category | v2 | v1 | Note |\n|---|---|---|---|\n")

	// The row is printed even when v2's cold start was not measured in this
	// run: a category left out reads as a category that does not matter.
	v2Cold := "not measured in this run"
	if len(cold) > 0 {
		v2Cold = fmt.Sprintf("%s to READY, then %s for the first request",
			humanDuration(cold[0].Latency.P50), humanDuration(warm[0].Latency.P50))
	}
	fmt.Fprintf(b, "| Cold vs cold | %s | %s per request, always | v1 is not a daemon: every request is a cold process plus a remote call |\n",
		v2Cold, humanDuration(v1[0].Latency.P50))
	fmt.Fprintf(b, "| Warm vs warm | %s p50 | not measurable with this binary | v1's engine can be kept warm in-process, but the SDK binary exits per request; the model call dominates either way |\n",
		humanDuration(warm[0].Latency.P50))
	fmt.Fprintf(b, "| Local vs remote | entirely local, no network on the request path | one remote generative call per request | different failure modes as well as different latencies |\n")

	v1RPS := 0.0
	if v1[0].Latency.Mean > 0 {
		v1RPS = float64(time.Second) / float64(v1[0].Latency.Mean)
	}
	best := 0.0
	for _, s := range r.Select("concurrency") {
		if s.RPS > best {
			best = s.RPS
		}
	}
	fmt.Fprintf(b, "| Single vs sustained | %.0f req/s sustained (best measured concurrency cell) | %.2f req/s serially, one process at a time | v1 was not driven concurrently: it would be measuring the provider's rate limits, not the architecture |\n\n",
		best, v1RPS)

	if v1[0].Latency.P50 > 0 && warm[0].Latency.P50 > 0 {
		ratio := float64(v1[0].Latency.P50) / float64(warm[0].Latency.P50)
		fmt.Fprintf(b, "**Warm local (v2) vs process-per-request remote (v1), p50:** %s vs %s, a factor of %.0f.\n",
			humanDuration(warm[0].Latency.P50), humanDuration(v1[0].Latency.P50), ratio)
		fmt.Fprintf(b, "That factor belongs to those two labels and no others.\n\n")
	}
}

func renderMethod(b *strings.Builder, r *Run) {
	fmt.Fprintf(b, "## Method\n\n")
	fmt.Fprintf(b, "- Every scenario runs against a warm engine assembled once: config, corpus,\n")
	fmt.Fprintf(b, "  model, index, pipeline. The worker process id is recorded before and after\n")
	fmt.Fprintf(b, "  each scenario to prove nothing respawned.\n")
	fmt.Fprintf(b, "- Latency is wall-clock around `pipeline.Run`; per-stage numbers come from\n")
	fmt.Fprintf(b, "  `pipeline.Stats`, the redacted telemetry, never from parsed output.\n")
	fmt.Fprintf(b, "- Percentiles are nearest-rank: every reported value is a latency that\n")
	fmt.Fprintf(b, "  actually occurred. p99 needs 100 samples to be meaningful, p95 needs 20;\n")
	fmt.Fprintf(b, "  under-sampled values are marked.\n")
	fmt.Fprintf(b, "- Throughput is completed requests over wall-clock time of the whole batch.\n")
	fmt.Fprintf(b, "- Scale configs are generated from a reviewed config (the Phase 7 commerce\n")
	fmt.Fprintf(b, "  schema) with synthetic entities appended; the core schema is byte-identical\n")
	fmt.Fprintf(b, "  at every scale and the synthetic entities never join to it.\n")
	fmt.Fprintf(b, "- No network is used on the request path; the embedding worker runs offline\n")
	fmt.Fprintf(b, "  by default (Phase 8, section 16.11).\n\n")
	fmt.Fprintf(b, "Reproduce:\n\n```bash\ncd v2\ngo run ./cmd/qf-bench --suite all\n```\n")
}

// ------------------------------------------------------------------ helpers

func humanDuration(d time.Duration) string {
	switch {
	case d == 0:
		return "-"
	case d < time.Microsecond:
		return fmt.Sprintf("%dns", d.Nanoseconds())
	case d < time.Millisecond:
		return fmt.Sprintf("%.1fus", float64(d.Nanoseconds())/1000)
	case d < time.Second:
		return fmt.Sprintf("%.1fms", float64(d.Nanoseconds())/1e6)
	case d < time.Minute:
		return fmt.Sprintf("%.2fs", d.Seconds())
	default:
		return fmt.Sprintf("%dm%02ds", int(d.Minutes()), int(d.Seconds())%60)
	}
}

func humanBytes(n int64) string {
	switch {
	case n <= 0:
		return "-"
	case n < 1<<20:
		return fmt.Sprintf("%.0f KB", float64(n)/(1<<10))
	case n < 1<<30:
		return fmt.Sprintf("%.1f MB", float64(n)/(1<<20))
	default:
		return fmt.Sprintf("%.2f GB", float64(n)/(1<<30))
	}
}

func sampleMark(underSampled bool) string {
	if underSampled {
		return "*"
	}
	return ""
}

func metMissed(ok bool) string {
	if ok {
		return "met"
	}
	return "**missed**"
}

func yesNo(ok bool) string {
	if ok {
		return "yes"
	}
	return "**no**"
}

func depthSuffix(s Scenario) string {
	if s.Name == "depth" && s.Depth != "" {
		return " (" + s.Depth + ")"
	}
	return ""
}

func orUnknown(s string) string {
	if strings.TrimSpace(s) == "" {
		return "unknown"
	}
	return s
}

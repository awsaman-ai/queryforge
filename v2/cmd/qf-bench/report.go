// Render turns a measured Run into the report section 17's manual gate asks
// for: hardware, OS, model, model version, schema size, test count and
// concurrency, then the numbers.
//
// Every table is generated from the raw samples in the run, so the report
// cannot drift from the measurement. Prose that requires judgement -- what a
// number means, whether a target was missed and why -- is written by hand in
// docs/phase-9-results.md and linked, not invented here.
func Render(r *Run) string {
	var b strings.Builder

	fmt.Fprintf(&b, "# Phase 9 performance report\n\n")
	fmt.Fprintf(&b, "Generated by `cmd/qf-bench` from `%s`. Every number below is computed from the\n", "benchmarks/scratch/results.json")
	fmt.Fprintf(&b, "raw samples in that file; nothing here is typed by hand.\n\n")

	renderEnvironment(&b, r)
	renderWarmArchitecture(&b, r)
	renderCold(&b, r)
	renderWarm(&b, r)
	renderStages(&b, r)
	renderDepth(&b, r)
	renderConcurrency(&b, r)
	renderResources(&b, r)
	renderInvariance(&b, r)
	renderV1(&b, r)
	renderMethod(&b, r)

	return b.String()
}

func renderEnvironment(b *strings.Builder, r *Run) {
	e := r.Environment
	fmt.Fprintf(b, "## Environment\n\n")
	fmt.Fprintf(b, "| | |\n|---|---|\n")
	fmt.Fprintf(b, "| Measured | %s |\n", r.StartedAt.Format("2006-01-02 15:04 MST"))
	fmt.Fprintf(b, "| Duration of the run | %s |\n", humanDuration(r.FinishedAt.Sub(r.StartedAt)))
	fmt.Fprintf(b, "| OS / arch | %s / %s |\n", e.OS, e.Arch)
	fmt.Fprintf(b, "| CPU | %s (%d logical cores) |\n", orUnknown(e.CPUModel), e.CPUs)
	if e.MemoryGB > 0 {
		fmt.Fprintf(b, "| Memory | %d GB |\n", e.MemoryGB)
	}
	fmt.Fprintf(b, "| Go | %s |\n", e.GoVersion)
	fmt.Fprintf(b, "| Embedding model | `%s` |\n", orUnknown(e.Model))
	fmt.Fprintf(b, "| Model revision | `%s` |\n", orUnknown(e.ModelRevision))
	fmt.Fprintf(b, "| Vector width | %d |\n", e.Dim)
	fmt.Fprintf(b, "| Semantic provider | %v |\n", e.Semantic)
	fmt.Fprintf(b, "| Index strategy | %s |\n", orUnknown(e.Strategy))
	fmt.Fprintf(b, "\n")
	if !e.Semantic && e.Model != "" {
		fmt.Fprintf(b, "> **Not a research result.** These vectors came from the deterministic\n")
		fmt.Fprintf(b, "> stand-in, not a semantic model.\n\n")
	}
	for _, n := range r.Notes {
		fmt.Fprintf(b, "> %s\n\n", n)
	}
}

// renderWarmArchitecture reports the structural requirement before any
// latency: if the model were reloaded per request, every number after this
// would be measuring the wrong system.
func renderWarmArchitecture(b *strings.Builder, r *Run) {
	fmt.Fprintf(b, "## Warm architecture (the prohibited pattern)\n\n")
	fmt.Fprintf(b, "Section 17 forbids spawning a model per request. Evidence, per scenario:\n\n")
	fmt.Fprintf(b, "| Scenario | Scale | Concurrency | Requests | One worker throughout | Worker pid |\n")
	fmt.Fprintf(b, "|---|---|---|---|---|---|\n")
	for _, s := range r.Scenarios {
		if s.Name == "cold" || s.Name == "cold-cached" || s.Name == "v1" {
			continue
		}
		fmt.Fprintf(b, "| %s%s | %s | %d | %d | %s | %d |\n",
			s.Name, depthSuffix(s), s.Scale.Label, s.Concurrency, s.Requests,
			yesNo(s.WorkerPIDStable), s.WorkerPID)
	}
	fmt.Fprintf(b, "\n")
}

func renderCold(b *strings.Builder, r *Run) {
	built := r.Select("cold")
	cached := r.Select("cold-cached")
	if len(built) == 0 && len(cached) == 0 {
		return
	}
	fmt.Fprintf(b, "## Cold start\n\n")
	fmt.Fprintf(b, "One \"cold start\" is the whole assembly: load config, build the corpus, load\n")
	fmt.Fprintf(b, "the model, build or load the index, construct the pipeline. Each row is %s\n", "a distribution over repeated starts")
	fmt.Fprintf(b, "of a fresh engine, including a fresh model process.\n\n")
	fmt.Fprintf(b, "| Index | Scale | Entries | Vectors | Starts | Ready p50 | Ready p95 | Ready max | Model load p50 | Index step p50 |\n")
	fmt.Fprintf(b, "|---|---|---|---|---|---|---|---|---|---|\n")
	for _, group := range [][]Scenario{built, cached} {
		for _, s := range group {
			kind := "built"
			if s.Name == "cold-cached" {
				kind = "cached"
			}
			fmt.Fprintf(b, "| %s | %s | %d | %d | %d | %s | %s | %s | %s | %s |\n",
				kind, s.Scale.Label, s.Scale.CorpusEntries, s.Scale.IndexVectors, s.Requests,
				humanDuration(s.Latency.P50), humanDuration(s.Latency.P95), humanDuration(s.Latency.Max),
				humanDuration(s.Stages["model_load"].P50), humanDuration(s.Stages["index"].P50))
		}
	}
	fmt.Fprintf(b, "\n")

	if len(built) > 0 && built[0].Cold != nil {
		c := built[0].Cold
		fmt.Fprintf(b, "Breakdown of the last cold start at %s: config %s, corpus %s, model %s, index %s, pipeline %s, **ready in %s**.\n\n",
			built[0].Scale.Label, humanDuration(c.ConfigLoad), humanDuration(c.CorpusBuild),
			humanDuration(c.ModelLoad), humanDuration(c.IndexBuild), humanDuration(c.PipelineNew), humanDuration(c.Ready))
	}
}

// Budgets from section 17. They are experimental targets, not guarantees, and
// the report states which were met rather than quietly omitting a miss.
var budgets = []struct {
	name string
	want time.Duration
	get  func(bench.Summary) time.Duration
}{
	{"p50", 50 * time.Millisecond, func(s bench.Summary) time.Duration { return s.P50 }},
	{"p95", 150 * time.Millisecond, func(s bench.Summary) time.Duration { return s.P95 }},
	{"p99", 300 * time.Millisecond, func(s bench.Summary) time.Duration { return s.P99 }},
}

func renderWarm(b *strings.Builder, r *Run) {
	warm := r.Select("warm")
	if len(warm) == 0 {
		return
	}
	fmt.Fprintf(b, "## Warm latency, sequential\n\n")
	fmt.Fprintf(b, "| Scale | Entries | Vectors | Requests | p50 | p95 | p99 | mean | min | max |\n")
	fmt.Fprintf(b, "|---|---|---|---|---|---|---|---|---|---|\n")
	for _, s := range warm {
		fmt.Fprintf(b, "| %s | %d | %d | %d | %s | %s%s | %s%s | %s | %s | %s |\n",
			s.Scale.Label, s.Scale.CorpusEntries, s.Scale.IndexVectors, s.Requests,
			humanDuration(s.Latency.P50),
			humanDuration(s.Latency.P95), sampleMark(s.Latency.P95UnderSampled),
			humanDuration(s.Latency.P99), sampleMark(s.Latency.P99UnderSampled),
			humanDuration(s.Latency.Mean), humanDuration(s.Latency.Min), humanDuration(s.Latency.Max))
	}
	fmt.Fprintf(b, "\n`*` marks a percentile with too few samples to mean more than \"the slowest request\".\n\n")

	fmt.Fprintf(b, "Against section 17's target budgets:\n\n")
	fmt.Fprintf(b, "| Scale | Target p50 <= 50ms | Target p95 <= 150ms | Target p99 <= 300ms |\n")
	fmt.Fprintf(b, "|---|---|---|---|\n")
	for _, s := range warm {
		fmt.Fprintf(b, "| %s |", s.Scale.Label)
		for _, budget := range budgets {
			got := budget.get(s.Latency)
			fmt.Fprintf(b, " %s (%s) |", metMissed(got <= budget.want), humanDuration(got))
		}
		fmt.Fprintf(b, "\n")
	}
	fmt.Fprintf(b, "\n")

	fmt.Fprintf(b, "Accepted queries and refusals measured apart, because a refusal stops early:\n\n")
	fmt.Fprintf(b, "| Scale | Accepted n | Accepted p50 | Accepted p95 | Refused n | Refused p50 | Refused p95 |\n")
	fmt.Fprintf(b, "|---|---|---|---|---|---|---|\n")
	for _, s := range warm {
		a, ref := s.LatencyByClass["accepted"], s.LatencyByClass["refused"]
		fmt.Fprintf(b, "| %s | %d | %s | %s | %d | %s | %s |\n", s.Scale.Label,
			a.N, humanDuration(a.P50), humanDuration(a.P95),
			ref.N, humanDuration(ref.P50), humanDuration(ref.P95))
	}
	fmt.Fprintf(b, "\n")
}

func renderStages(b *strings.Builder, r *Run) {
	warm := r.Select("warm")
	if len(warm) == 0 {
		return
	}
	fmt.Fprintf(b, "## Where the time goes\n\n")
	fmt.Fprintf(b, "Per-stage latency from `pipeline.Stats` (accepted requests only), and each\n")
	fmt.Fprintf(b, "stage's mean as a share of the mean total.\n\n")
	for _, s := range warm {
		if len(s.Stages) == 0 {
			continue
		}
		fmt.Fprintf(b, "**%s entries**\n\n", s.Scale.Label)
		fmt.Fprintf(b, "| Stage | p50 | p95 | mean | share of total |\n|---|---|---|---|---|\n")
		for _, name := range []string{"extract", "retrieve", "rank", "bind", "plan", "compile"} {
			sum, ok := s.Stages[name]
			if !ok {
				continue
			}
			fmt.Fprintf(b, "| %s | %s | %s | %s | %.1f%% |\n", name,
				humanDuration(sum.P50), humanDuration(sum.P95), humanDuration(sum.Mean),
				s.StageShares[name]*100)
		}
		if total, ok := s.Stages["total_measured_in_pipeline"]; ok {
			fmt.Fprintf(b, "| **total (in pipeline)** | %s | %s | %s | |\n",
				humanDuration(total.P50), humanDuration(total.P95), humanDuration(total.Mean))
		}
		fmt.Fprintf(b, "\n")
	}

	// The retrieval stage is two different costs -- a round trip to the model
	// and a scan of the index -- and section 17 asks about them separately
	// ("vector lookup should be a small fraction of total latency"). Stats
	// cannot answer that; the harness's own retriever times both halves.
	fmt.Fprintf(b, "### Retrieval split: model round trip vs vector scan\n\n")
	fmt.Fprintf(b, "Means per request, measured inside the retriever.\n\n")
	fmt.Fprintf(b, "| Scale | Vectors | Embedding | Vector search | Scans per request | Search share of request |\n")
	fmt.Fprintf(b, "|---|---|---|---|---|---|\n")
	for _, s := range warm {
		if s.EmbedPerRequest == 0 && s.SearchPerRequest == 0 {
			continue
		}
		share := 0.0
		if s.Latency.Mean > 0 {
			share = float64(s.SearchPerRequest) / float64(s.Latency.Mean)
		}
		fmt.Fprintf(b, "| %s | %d | %s | %s | %.1f | %.1f%% |\n", s.Scale.Label, s.Scale.IndexVectors,
			humanDuration(s.EmbedPerRequest), humanDuration(s.SearchPerRequest),
			s.SearchesPerRequest, share*100)
	}
	fmt.Fprintf(b, "\n")
}

